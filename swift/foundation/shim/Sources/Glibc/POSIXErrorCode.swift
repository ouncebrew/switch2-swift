// such overlay exists for a bare-metal target, so this module supplies it.
//
// 89 of Foundation's 90 codes come straight from newlib's
// <sys/errno.h>; the values are read out of that header when this file is
// generated rather than copied by hand, so they cannot disagree with the
// errno the console actually sets. The remainder of Foundation's list is
// Darwin- or RPC-specific (EBADMACHO, ERPCMISMATCH and so on) and is already
// excluded by Foundation's own `#if canImport(Darwin)`.
//
// Generated by swift/foundation/build-foundation.sh. Do not edit by hand.
//
//===----------------------------------------------------------------------===//

